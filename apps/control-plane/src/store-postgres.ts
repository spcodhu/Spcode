const NUMERIC_FIELDS = new Set([
  "revision",
  "fence",
  "lease_fence",
  "created_at",
  "updated_at",
  "received_at",
  "expires_at",
  "heartbeat_at",
  "lease_expires_at",
  "next_run_at",
  "last_seen_at",
  "last_success_at",
  "completed_at",
  "last_heartbeat_at",
  "revoked_at",
  "resolved_at",
  "attempt_count",
  "item_count",
  "count",
  "n",
  "next",
  "size",
  "rowCount",
  "last_event_seq",
  "snapshot_version",
]);

interface Statement {
  text: string;
  values: unknown[];
}

function statement(sql: string, params: unknown[]): Statement {
  return { text: sql, values: params.length === 1 && Array.isArray(params[0]) ? (params[0] as unknown[]) : params };
}

function normalizeRow(row: Record<string, unknown>): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(row)) {
    if (typeof value === "string" && NUMERIC_FIELDS.has(key) && /^-?\d+(?:\.\d+)?$/.test(value))
      result[key] = Number(value);
    else result[key] = value;
  }
  return result;
}

class PostgresDatabaseAdapter {
  constructor(private readonly client: PostgresSyncClient) {}

  prepare(sql: string) {
    return {
      run: (...params: unknown[]) => {
        const input = statement(sql, params);
        const needsId =
          /^\s*INSERT\s+INTO\s+(?:events|audit_log|worker_events)\b/i.test(input.text) &&
          !/\bRETURNING\b/i.test(input.text);
        const result = this.client.query(`${input.text}${needsId ? " RETURNING id" : ""}`, input.values);
        return {
          changes: result.rowCount ?? result.rows.length,
          lastInsertRowid: result.rows[0]?.id ?? 0,
        };
      },
      get: (...params: unknown[]) => {
        const input = statement(sql, params);
        const result = this.client.query(input.text, input.values);
        return result.rows[0] ? normalizeRow(result.rows[0]) : undefined;
      },
      all: (...params: unknown[]) => {
        const input = statement(sql, params);
        return this.client.query(input.text, input.values).rows.map(normalizeRow);
      },
    };
  }

  exec(sql: string): void {
    this.client.query(sql);
  }

  close(): void {
    // 连接由 PostgresSuperAgentStore 统一关闭；此处满足基类清理端口。
  }
}

