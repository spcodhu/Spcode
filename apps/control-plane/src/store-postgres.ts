export interface PostgresStoreOptions {
  connectionString: string;
  baseDir: string;
  workerFile: URL;
}

/** 与 SQLite 共用领域方法的 PostgreSQL Store；连接串只传 worker，不写日志或 Artifact。 */
export class PostgresSuperAgentStore extends SqliteSuperAgentStore {
  private readonly pg: PostgresSyncClient;

  constructor(options: PostgresStoreOptions) {
    super(":memory:");
    this.pg = new PostgresSyncClient(options.connectionString, options.workerFile);
    const adapter = new PostgresDatabaseAdapter(this.pg);
    adapter.exec(postgresSchema());
    Object.defineProperty(this, "db", {
      value: adapter as unknown as DatabaseSync,
      configurable: false,
      writable: false,
    });
    Object.defineProperty(this, "artifacts", {
      value: new ArtifactStore(join(options.baseDir, "artifacts"), adapter as unknown as DatabaseSync),
      configurable: false,
      writable: false,
    });
  }

  override close(): void {
    this.pg.close();
    super.close();
  }
}
